#!/usr/bin/env node
// 从 contracts/enums.json + server/contracts.mjs 生成三样东西：
//   1. contracts/schema/*.schema.json   —— 给人看的 JSON Schema（也是测试夹具的校验器）
//   2. bridge/src/Contracts.Generated.cs —— 桥接器用的常量（C# 5）
//   3. tools 自检：任何一边改了词表，--check 会失败，而不是等到运行时才暴露。
//
// 用法：
//   node tools/gen-contracts.mjs           # 写入
//   node tools/gen-contracts.mjs --check   # 只比较，不写；过期则退出码 1
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { ENUMS, jsonSchemas } from '../server/contracts.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const schemaDir = join(root, 'contracts', 'schema')
const csPath = join(root, 'bridge', 'src', 'Contracts.Generated.cs')

function pascal(value) {
  return String(value)
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
}

function escapeCs(text) {
  return String(text).replace(/\\/g, '\\\\').replace(/"/g, '\\"')
}

function csStrings(values, indent = '            ') {
  return values.map((value) => `${indent}public const string ${pascal(value)} = "${escapeCs(value)}";`).join('\n')
}

function csArray(name, values) {
  const items = values.map((value) => `"${escapeCs(value)}"`).join(', ')
  return `        public static readonly string[] ${name} = new string[] { ${items} };`
}

export function renderCSharp(enums) {
  const terminal = enums.terminalJobStates
  const lines = []
  lines.push('// <auto-generated>')
  lines.push('// Generated by tools/gen-contracts.mjs from contracts/enums.json. Do not edit.')
  lines.push('// Run: node tools/gen-contracts.mjs')
  lines.push('namespace SwMcp')
  lines.push('{')
  lines.push('    /// <summary>Contract constants shared with server/contracts.mjs.</summary>')
  lines.push('    static class Contracts')
  lines.push('    {')
  lines.push(`        public const int SchemaVersion = ${enums.schemaVersion};`)
  lines.push(`        public const int ProtocolVersion = ${enums.protocolVersion};`)
  lines.push(`        public const string BridgeVersion = "${escapeCs(enums.bridgeVersion)}";`)
  lines.push(`        public const string UnitLength = "${escapeCs(enums.units.length)}";`)
  lines.push(`        public const string UnitAngle = "${escapeCs(enums.units.angle)}";`)
  lines.push('')
  lines.push(csArray('RefKinds', enums.refKinds))
  lines.push(csArray('JobStates', enums.jobStates))
  lines.push(csArray('TerminalJobStates', terminal))
  lines.push(csArray('TaskStates', enums.taskStates))
  lines.push(csArray('CurveKinds', enums.curveKinds))
  lines.push(csArray('CurveSources', enums.curveSources))
  lines.push(csArray('ConstraintTypes', enums.constraintTypes))
  lines.push(csArray('DimensionTypes', enums.dimensionTypes))
  lines.push(csArray('FileKinds', enums.fileKinds))
  lines.push(csArray('Severities', enums.severities))
  lines.push(csArray('EvidenceKinds', enums.evidenceKinds))
  lines.push(csArray('ExperienceKinds', enums.experienceKinds))
  lines.push(csArray('ExperienceStatuses', enums.experienceStatus))
  lines.push(csArray('EventNames', enums.eventNames))
  lines.push('')
  lines.push('        public static class RefKind')
  lines.push('        {')
  lines.push(csStrings(enums.refKinds))
  lines.push('        }')
  lines.push('')
  lines.push('        public static class JobState')
  lines.push('        {')
  lines.push(csStrings(enums.jobStates))
  lines.push('        }')
  lines.push('')
  lines.push('        public static class TaskState')
  lines.push('        {')
  lines.push(csStrings(enums.taskStates))
  lines.push('        }')
  lines.push('')
  lines.push('        public static class CurveKind')
  lines.push('        {')
  lines.push(csStrings(enums.curveKinds))
  lines.push('        }')
  lines.push('')
  lines.push('        public static class ErrorCode')
  lines.push('        {')
  lines.push(csStrings(enums.errorCodes))
  lines.push('        }')
  lines.push('')
  lines.push('        public static class Event')
  lines.push('        {')
  lines.push(csStrings(enums.eventNames))
  lines.push('        }')
  lines.push('')
  lines.push('        public static bool IsTerminalJobState(string state)')
  lines.push('        {')
  lines.push('            for (int i = 0; i < TerminalJobStates.Length; i++)')
  lines.push('                if (TerminalJobStates[i] == state) return true;')
  lines.push('            return false;')
  lines.push('        }')
  lines.push('')
  lines.push('        public static bool IsCurveKind(string kind)')
  lines.push('        {')
  lines.push('            for (int i = 0; i < CurveKinds.Length; i++)')
  lines.push('                if (CurveKinds[i] == kind) return true;')
  lines.push('            return false;')
  lines.push('        }')
  lines.push('    }')
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

function schemaFiles() {
  const schemas = jsonSchemas()
  const files = {}
  for (const [name, schema] of Object.entries(schemas)) {
    files[join('contracts', 'schema', `${name}.schema.json`)] = `${JSON.stringify(schema, null, 2)}\n`
  }
  files[join('bridge', 'src', 'Contracts.Generated.cs')] = renderCSharp(ENUMS)
  return files
}

/**
 * Generate or compare every artifact.
 * @returns {{changed:boolean, files:Array<{path:string,status:'same'|'written'|'stale'}>}}
 */
export function generateContracts({ check = false } = {}) {
  const files = schemaFiles()
  const report = []
  let changed = false
  if (!check) mkdirSync(schemaDir, { recursive: true })
  for (const [relPath, content] of Object.entries(files)) {
    const full = join(root, relPath)
    const exists = existsSync(full)
    const current = exists ? readFileSync(full, 'utf8') : null
    if (current === content) {
      report.push({ path: relPath, status: 'same' })
      continue
    }
    changed = true
    if (check) {
      report.push({ path: relPath, status: 'stale' })
    } else {
      mkdirSync(dirname(full), { recursive: true })
      writeFileSync(full, content, 'utf8')
      report.push({ path: relPath, status: 'written' })
    }
  }
  return { root, changed, files: report }
}

const isMain = process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url
if (isMain) {
  const check = process.argv.includes('--check')
  const result = generateContracts({ check })
  for (const file of result.files) {
    if (file.status === 'same') continue
    const label = file.status === 'stale' ? 'STALE  ' : 'wrote  '
    console.log(`${label}${relative(process.cwd(), join(result.root, file.path))}`)
  }
  if (check && result.changed) {
    console.error('contracts are stale: run node tools/gen-contracts.mjs')
    process.exit(1)
  }
  if (!result.changed) console.log('contracts up to date')
}
